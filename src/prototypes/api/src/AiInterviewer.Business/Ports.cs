/// <summary>A collaborator could not be reached. The use case turns this into an explicit error state.</summary>
public sealed class PortUnavailableException(string message) : Exception(message);

/// <summary>
/// Where a stored document came from: the user's upload, or a sample set loaded by key, so loading
/// the same samples again adds nothing (Adapters/Samples). The key is never blank.
/// </summary>
public sealed record DocumentSource
{
    public string Key { get; }
    private DocumentSource(string key) => Key = key;

    /// <summary>A document the user uploaded or pasted.</summary>
    public static DocumentSource Upload { get; } = new("upload");

    /// <summary>A document from a sample set: "sample:{key}", for example "sample:personas:RET-01:role".</summary>
    public static Outcome<DocumentSource> Sample(string key) => From(key).Select(k => new DocumentSource($"sample:{k.Key}"));

    public static Outcome<DocumentSource> From(string raw) => NonBlank.Check(raw, nameof(DocumentSource)) switch
    {
        Succeeded<string> ok => Outcome.Success(new DocumentSource(ok.Value)),
        Failed<string> bad => Outcome.Failure<DocumentSource>(bad.Message),
        _ => throw new InvalidOperationException(),
    };

    public override string ToString() => Key;
}

/// <summary>A resume or a role. For a role, <paramref name="Text"/> is its description (the job description as uploaded).</summary>
public sealed record StoredDocument<TId>(TId Id, DisplayName Name, DateTimeOffset ProcessedAt, string Text, DocumentSource Source);

public interface IDocumentStore<TId>
{
    /// <summary>Most recently processed first, as the setup page lists them.</summary>
    Task<IReadOnlyList<StoredDocument<TId>>> ListAsync(CancellationToken ct);

    Task<bool> ContainsAsync(TId id, CancellationToken ct);

    Task<Outcome<StoredDocument<TId>>> FindAsync(TId id, CancellationToken ct);

    /// <summary>Whether a document from that source was added before, so a sample set is loaded once.</summary>
    Task<bool> ContainsSourceAsync(DocumentSource source, CancellationToken ct);

    Task<TId> AddAsync(DisplayName name, string text, DateTimeOffset processedAt, DocumentSource source, CancellationToken ct);
}

public interface IResumeStore : IDocumentStore<ResumeId>;

public interface IRoleStore : IDocumentStore<RoleId>;

/// <summary>
/// A role's questions (Setup/Questions.cs). A set is stored first and becomes the role's questions
/// when it is activated, so an upload can wait for Prepare interview, which is when the spec says
/// saved questions are purged. Question ids are generated by the store.
/// </summary>
public interface IQuestionStore
{
    /// <summary>The role's current questions, in order. Empty when it has none.</summary>
    Task<IReadOnlyList<InterviewQuestion>> ListAsync(RoleId role, CancellationToken ct);

    /// <summary>Stores a set without making it the role's questions.</summary>
    Task<QuestionSetId> AddSetAsync(RoleId role, QuestionSource source, IReadOnlyList<string> texts, DateTimeOffset createdAt, CancellationToken ct);

    Task<Outcome<QuestionSet>> FindSetAsync(QuestionSetId id, CancellationToken ct);

    /// <summary>Makes the set the role's questions and purges the role's previous ones. Throws for a set this store does not have.</summary>
    Task ActivateAsync(QuestionSetId id, CancellationToken ct);

    /// <summary>Removes the role's current questions. A role without questions is left as it is.</summary>
    Task PurgeAsync(RoleId role, CancellationToken ct);
}

