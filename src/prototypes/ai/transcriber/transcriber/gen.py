"""Generates the gRPC stubs from contracts/ai/transcription.proto into transcriber/generated/.

Run once after cloning and after every change to the proto: `python -m transcriber.gen`.
The output is not committed; the proto is the source of truth (decision 0003, open item 5).
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CONTRACTS = HERE.parents[4] / "contracts" / "ai"
OUT = HERE / "generated"


def main() -> int:
    from grpc_tools import protoc

    OUT.mkdir(exist_ok=True)
    (OUT / "__init__.py").write_text("# Generated by transcriber.gen from contracts/ai/transcription.proto. Do not edit.\n")
    code = protoc.main(
        [
            "protoc",
            f"-I{CONTRACTS}",
            f"--python_out={OUT}",
            f"--pyi_out={OUT}",
            f"--grpc_python_out={OUT}",
            str(CONTRACTS / "transcription.proto"),
        ]
    )
    if code != 0:
        return code
    # grpc_tools writes `import transcription_pb2`; make it a relative import so the package imports from anywhere.
    grpc_file = OUT / "transcription_pb2_grpc.py"
    grpc_file.write_text(grpc_file.read_text().replace("import transcription_pb2 as", "from . import transcription_pb2 as"))
    print(f"generated into {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
